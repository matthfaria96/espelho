#!/usr/bin/env python3 -I
"""Writes Espelho/Resources/Localizations/<lang>.lproj from scripts/translations.py.

  python3 scripts/make-localizations.py            # write the .lproj folders
  python3 scripts/make-localizations.py --check    # also build, and list keys that lack a translation

English (en) is the development region, so any language without its own folder gets English.
pt-BR maps every key to itself (the Swift code is written in Portuguese).
"""
import glob
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from translations import INFO_PLIST, LANGUAGES, T  # noqa: E402

ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "Espelho", "Resources", "Localizations")
HEADER = "/* Generated by scripts/make-localizations.py from scripts/translations.py; do not edit. */\n\n"


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write(language, table, info):
    folder = os.path.join(OUT, f"{language}.lproj")
    os.makedirs(folder, exist_ok=True)
    for name, entries in (("Localizable.strings", table), ("InfoPlist.strings", info)):
        lines = [f'"{escape(k)}" = "{escape(v)}";' for k, v in sorted(entries.items())]
        with open(os.path.join(folder, name), "w", encoding="utf-8") as handle:
            handle.write(HEADER + "\n".join(lines) + "\n")


def code_keys():
    """Every key the compiler sees in Text, Button, String(localized:)… (needs Xcode's toolchain)."""
    out = tempfile.mkdtemp()
    env = dict(os.environ, DEVELOPER_DIR=os.environ.get("DEVELOPER_DIR", "/Applications/Xcode.app/Contents/Developer"))
    subprocess.run(["swift", "build", "--package-path", os.path.join(ROOT, "Espelho"),
                    "-Xswiftc", "-emit-localized-strings", "-Xswiftc", "-emit-localized-strings-path", "-Xswiftc", out],
                   check=True, env=env, stdout=subprocess.DEVNULL)
    keys = set()
    for path in glob.glob(os.path.join(out, "*.stringsdata")):
        for entries in json.load(open(path)).get("tables", {}).values():
            keys.update(entry["key"] for entry in entries)
    return keys


def main():
    for i, language in enumerate(LANGUAGES):
        write(language, {k: v[i] for k, v in T.items()}, {k: v[i] for k, v in INFO_PLIST.items()})
    write("pt-BR", {k: k for k in T}, {k: v[len(LANGUAGES)] for k, v in INFO_PLIST.items()})
    print(f"{len(T)} textos em {', '.join(LANGUAGES + ['pt-BR'])}")

    if "--check" in sys.argv:
        # Keys with no letters to translate (numbers, %@, brand names) may stay out of the table.
        neutral = {"%@", "%lld", "·", "000000", "15", "30", "60", "7 ✓", "7.0", "9:41", "AP3A.240905.015",
                   "Android", "Espelho", "GitHub", "Mac", "Samsung", "Xiaomi, Redmi, POCO", "witchmymac.com"}
        keys = code_keys()
        missing = sorted(keys - set(T) - neutral)
        unused = sorted(set(T) - keys)
        for key in missing:
            print("falta traduzir:", repr(key))
        for key in unused:
            print("não usado no código:", repr(key))
        sys.exit(1 if missing else 0)


if __name__ == "__main__":
    main()
